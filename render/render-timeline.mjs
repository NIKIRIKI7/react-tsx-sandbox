import path from 'node:path';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileTailwindCss } from './tailwind-v4.mjs';
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const sceneFile = path.join(projectRoot, 'examples', 'data-driven-timeline.tsx');
const generatedDir = path.join(here, '.generated');
const publicAudioDir = path.join(here, 'public', 'audio');
const outDir = path.join(here, 'out');

const STILL_FRAMES = [45, 90, 150, 210];

// Медиа-ассеты, на которые переписываются удалённые URL из примера.
const AUDIO_ASSETS = [
  {
    file: 'music.mp3',
    url: 'https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3',
  },
  {
    file: 'voice.mp3',
    url: 'https://www.soundhelix.com/examples/mp3/SoundHelix-Song-2.mp3',
  },
  {
    file: 'pop.ogg',
    url: 'https://actions.google.com/sounds/v1/cartoon/pop.ogg',
  },
  {
    file: 'beep.ogg',
    url: 'https://actions.google.com/sounds/v1/alarms/beep_short.ogg',
  },
];

// Прямые замены «https://...» -> staticFile('audio/...').
const SRC_REWRITES = [
  ['https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3', 'audio/music.mp3'],
  ['https://www.soundhelix.com/examples/mp3/SoundHelix-Song-2.mp3', 'audio/voice.mp3'],
  ['https://actions.google.com/sounds/v1/cartoon/pop.ogg', 'audio/pop.ogg'],
  ['https://actions.google.com/sounds/v1/alarms/beep_short.ogg', 'audio/beep.ogg'],
];

for (const dir of [generatedDir, publicAudioDir, outDir]) mkdirSync(dir, { recursive: true });
if (!existsSync(sceneFile)) throw new Error(`Scene not found: ${sceneFile}`);

console.log('[timeline] ensuring audio assets...');
for (const asset of AUDIO_ASSETS) {
  const target = path.join(publicAudioDir, asset.file);
  if (existsSync(target) && statSync(target).size > 0) {
    console.log('[timeline] cached:', asset.file, statSync(target).size, 'bytes');
    continue;
  }
  const response = await fetch(asset.url);
  if (!response.ok) throw new Error(`Failed to download ${asset.url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  writeFileSync(target, bytes);
  console.log('[timeline] downloaded:', asset.file, bytes.length, 'bytes');
}

// Переписываем удалённые URL на локальные ассеты через staticFile (global в песочнице).
let source = readFileSync(sceneFile, 'utf8');
for (const [remoteUrl, localFile] of SRC_REWRITES) {
  const needle = `'${remoteUrl}'`;
  const replacement = `staticFile('${localFile}')`;
  if (!source.includes(needle)) {
    throw new Error(`Remote URL not found in scene: ${remoteUrl}`);
  }
  source = source.split(needle).join(replacement);
}

console.log('[timeline] compiling tailwind utilities...');
const tailwindCss = await compileTailwindCss(source);

writeFileSync(
  path.join(generatedDir, 'timeline-scene.ts'),
  `// AUTO-GENERATED by render/render-timeline.mjs. Do not edit.\n` +
    `export const source = ${JSON.stringify(source)};\n` +
    `export const css = ${JSON.stringify(tailwindCss)};\n`,
);
console.log('[timeline] css bytes:', tailwindCss.length);

console.log('[timeline] bundling...');
const serveUrl = await bundle({
  entryPoint: path.join(here, 'entry-timeline.tsx'),
  publicDir: path.join(here, 'public'),
  outDir: path.join(here, 'bundle-timeline'),
  onProgress: (progress) => process.stdout.write(`\r[timeline] bundling ${progress}%   `),
});
console.log('\n[timeline] bundle ready');

const browserExecutable = [
  process.env.REMOTION_BROWSER,
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
].find((candidate) => candidate && existsSync(candidate));
if (!browserExecutable) throw new Error('Chrome not found. Set REMOTION_BROWSER.');

const composition = await selectComposition({ serveUrl, id: 'TimelineDemo', browserExecutable });
console.log('[timeline] composition:', composition.id, composition.width, 'x', composition.height);

for (const frame of STILL_FRAMES) {
  const output = path.join(outDir, `timeline-frame-${String(frame).padStart(3, '0')}.png`);
  await renderStill({ serveUrl, composition, output, frame, browserExecutable });
  console.log('[timeline] still', frame, '->', statSync(output).size, 'bytes');
}

const videoPath = path.join(outDir, 'data-driven-timeline.mp4');
await renderMedia({
  serveUrl,
  composition,
  codec: 'h264',
  outputLocation: videoPath,
  browserExecutable,
  onProgress: ({ progress }) =>
    process.stdout.write(`\r[timeline] video ${Math.round(progress * 100)}%   `),
});
console.log('\n[timeline] video:', videoPath, statSync(videoPath).size, 'bytes');
console.log('[timeline] DONE');
