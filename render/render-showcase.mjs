import path from 'node:path';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileTailwindCss } from './tailwind-v4.mjs';
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';

const here = path.dirname(fileURLToPath(import.meta.url));
const generatedDir = path.join(here, '.generated');
const publicDir = path.join(here, 'public');
const outDir = path.join(here, 'out');
const sceneFile = path.join(here, 'showcase-scene.tsx');

const STILL_FRAMES = [30, 75];

for (const dir of [generatedDir, publicDir, outDir]) mkdirSync(dir, { recursive: true });

if (!existsSync(sceneFile)) throw new Error(`Scene not found: ${sceneFile}`);
const source = readFileSync(sceneFile, 'utf8');

// Tailwind-утилиты, использованные в сцене.
console.log('[showcase] compiling tailwind utilities...');
const tailwindCss = await compileTailwindCss(source);

writeFileSync(
  path.join(generatedDir, 'showcase-css.ts'),
  `// AUTO-GENERATED by render/render-showcase.mjs. Do not edit.\n` +
    `export const css = ${JSON.stringify(tailwindCss)};\n`,
);
writeFileSync(
  path.join(generatedDir, 'showcase-scene.ts'),
  `// AUTO-GENERATED by render/render-showcase.mjs. Do not edit.\n` +
    `export const source = ${JSON.stringify(source)};\n`,
);
console.log('[showcase] css bytes:', tailwindCss.length);

console.log('[showcase] bundling...');
const serveUrl = await bundle({
  entryPoint: path.join(here, 'entry-showcase.tsx'),
  publicDir,
  outDir: path.join(here, 'bundle-showcase'),
  onProgress: (progress) => process.stdout.write(`\r[showcase] bundling ${progress}%   `),
});
console.log('\n[showcase] bundle ready');

const browserExecutable = [
  process.env.REMOTION_BROWSER,
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
].find((candidate) => candidate && existsSync(candidate));
if (!browserExecutable) throw new Error('Chrome not found. Set REMOTION_BROWSER.');

const composition = await selectComposition({ serveUrl, id: 'Showcase', browserExecutable });
console.log('[showcase] composition:', composition.width, 'x', composition.height);

for (const frame of STILL_FRAMES) {
  const output = path.join(outDir, `showcase-frame-${String(frame).padStart(3, '0')}.png`);
  await renderStill({ serveUrl, composition, output, frame, browserExecutable });
  console.log('[showcase] still', frame, '->', statSync(output).size, 'bytes');
}

const videoPath = path.join(outDir, 'showcase.mp4');
await renderMedia({
  serveUrl,
  composition,
  codec: 'h264',
  outputLocation: videoPath,
  browserExecutable,
  onProgress: ({ progress }) =>
    process.stdout.write(`\r[showcase] video ${Math.round(progress * 100)}%   `),
});
console.log('\n[showcase] video:', videoPath, statSync(videoPath).size, 'bytes');
console.log('[showcase] DONE');
