import path from 'node:path';
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileTailwindCss } from './tailwind-v4.mjs';
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const sceneFile = path.join(projectRoot, 'examples', 'voiceover-animation.tsx');
const voiceSource = path.join(projectRoot, 'examples', 'voice', 'voice_01.wav');
const generatedDir = path.join(here, '.generated');
const publicAudioDir = path.join(here, 'public', 'audio');
const publicVoiceDir = path.join(here, 'public', 'voice');
const outDir = path.join(here, 'out');

const STILL_FRAMES = [45, 90, 165, 255];

// Локальные/удалённые аудио-ассеты, на которые переписываются URL из примера.
const AUDIO_ASSETS = [
  { file: 'music.mp3', url: 'https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3' },
  { file: 'pop.ogg', url: 'https://actions.google.com/sounds/v1/cartoon/pop.ogg' },
  { file: 'beep.ogg', url: 'https://actions.google.com/sounds/v1/alarms/beep_short.ogg' },
];

const SRC_REWRITES = [
  ['https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3', 'audio/music.mp3'],
  ['https://actions.google.com/sounds/v1/cartoon/pop.ogg', 'audio/pop.ogg'],
  ['https://actions.google.com/sounds/v1/alarms/beep_short.ogg', 'audio/beep.ogg'],
];

for (const dir of [generatedDir, publicAudioDir, publicVoiceDir, outDir]) {
  mkdirSync(dir, { recursive: true });
}
if (!existsSync(sceneFile)) throw new Error(`Scene not found: ${sceneFile}`);
if (!existsSync(voiceSource)) throw new Error(`Voiceover not found: ${voiceSource}`);

// Реальная озвучка пользователя -> public для `staticFile('voice/voice_01.wav')`.
const voiceTarget = path.join(publicVoiceDir, 'voice_01.wav');
copyFileSync(voiceSource, voiceTarget);
console.log('[voiceover] voice:', voiceTarget, statSync(voiceTarget).size, 'bytes');

console.log('[voiceover] ensuring music/sfx assets...');
for (const asset of AUDIO_ASSETS) {
  const target = path.join(publicAudioDir, asset.file);
  if (existsSync(target) && statSync(target).size > 0) {
    console.log('[voiceover] cached:', asset.file, statSync(target).size, 'bytes');
    continue;
  }
  const response = await fetch(asset.url);
  if (!response.ok) throw new Error(`Failed to download ${asset.url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  writeFileSync(target, bytes);
  console.log('[voiceover] downloaded:', asset.file, bytes.length, 'bytes');
}

let source = readFileSync(sceneFile, 'utf8');
for (const [remoteUrl, localFile] of SRC_REWRITES) {
  const needle = `'${remoteUrl}'`;
  if (!source.includes(needle)) throw new Error(`Remote URL not found in scene: ${remoteUrl}`);
  source = source.split(needle).join(`staticFile('${localFile}')`);
}

console.log('[voiceover] compiling tailwind utilities...');
const tailwindCss = await compileTailwindCss(source);

writeFileSync(
  path.join(generatedDir, 'voiceover-scene.ts'),
  `// AUTO-GENERATED by render/render-voiceover.mjs. Do not edit.\n` +
    `export const source = ${JSON.stringify(source)};\n` +
    `export const css = ${JSON.stringify(tailwindCss)};\n`,
);
console.log('[voiceover] css bytes:', tailwindCss.length);

console.log('[voiceover] bundling...');
const serveUrl = await bundle({
  entryPoint: path.join(here, 'entry-voiceover.tsx'),
  publicDir: path.join(here, 'public'),
  outDir: path.join(here, 'bundle-voiceover'),
  onProgress: (progress) => process.stdout.write(`\r[voiceover] bundling ${progress}%   `),
});
console.log('\n[voiceover] bundle ready');

const browserExecutable = [
  process.env.REMOTION_BROWSER,
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
].find((candidate) => candidate && existsSync(candidate));
if (!browserExecutable) throw new Error('Chrome not found. Set REMOTION_BROWSER.');

const composition = await selectComposition({ serveUrl, id: 'VoiceoverAnimation', browserExecutable });
console.log('[voiceover] composition:', composition.id, composition.width, 'x', composition.height);

for (const frame of STILL_FRAMES) {
  const output = path.join(outDir, `voiceover-frame-${String(frame).padStart(3, '0')}.png`);
  await renderStill({ serveUrl, composition, output, frame, browserExecutable });
  console.log('[voiceover] still', frame, '->', statSync(output).size, 'bytes');
}

const videoPath = path.join(outDir, 'voiceover-animation.mp4');
await renderMedia({
  serveUrl,
  composition,
  codec: 'h264',
  outputLocation: videoPath,
  browserExecutable,
  onProgress: ({ progress }) =>
    process.stdout.write(`\r[voiceover] video ${Math.round(progress * 100)}%   `),
});
console.log('\n[voiceover] video:', videoPath, statSync(videoPath).size, 'bytes');
console.log('[voiceover] DONE');
