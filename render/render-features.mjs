import path from 'node:path';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const generatedDir = path.join(here, '.generated');
const outDir = path.join(here, 'out');

const SCENE_FILES = {
  tailwindSource: path.join(projectRoot, 'examples', 'tailwind-jit-scene.tsx'),
  hmrSource: path.join(projectRoot, 'examples', 'hmr-module-graph-scene.tsx'),
  exportSource: path.join(projectRoot, 'examples', 'export-pipeline-scene.tsx'),
  hmrVfsFile: path.join(projectRoot, 'examples', 'hmr-sandbox.vfs.json'),
};

const COMPOSITIONS = {
  FeaturesTailwind: { frames: [60, 120] },
  FeaturesHmr: { frames: [80, 140] },
  FeaturesExportPipeline: { frames: [30, 90, 140], video: 'features-pipeline.mp4' },
};

function loadSceneSources() {
  const sources = {};
  for (const [key, file] of Object.entries(SCENE_FILES)) {
    if (!existsSync(file)) throw new Error(`Scene not found: ${file}`);
    if (key === 'hmrVfsFile') {
      sources.hmrVfs = JSON.parse(readFileSync(file, 'utf8'));
    } else {
      sources[key] = readFileSync(file, 'utf8');
    }
  }
  return sources;
}

function writeGenerated(sources) {
  const hmrVfsHot = {
    '/labels.ts': `export const label = 'hot-reloaded v2';\nexport const beats = 128;\n`,
  };
  const content =
    `// AUTO-GENERATED by render/render-features.mjs. Do not edit.\n` +
    `export const tailwindSource = ${JSON.stringify(sources.tailwindSource)};\n` +
    `export const hmrSource = ${JSON.stringify(sources.hmrSource)};\n` +
    `export const exportSource = ${JSON.stringify(sources.exportSource)};\n` +
    `export const hmrVfs = ${JSON.stringify(sources.hmrVfs)};\n` +
    `export const hmrVfsHot = ${JSON.stringify(hmrVfsHot)};\n`;
  writeFileSync(path.join(generatedDir, 'features-scenes.ts'), content);
  return content.length;
}

mkdirSync(generatedDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

console.log('[features] reading scene sources...');
const sources = loadSceneSources();
writeGenerated(sources);
console.log('[features] generated .generated/features-scenes.ts');
console.log('[features] hmr vfs files:', Object.keys(sources.hmrVfs).join(', '));

console.log('[features] bundling...');
const serveUrl = await bundle({
  entryPoint: path.join(here, 'entry-features.tsx'),
  outDir: path.join(here, 'bundle-features'),
  onProgress: (progress) => process.stdout.write(`\r[features] bundling ${progress}%   `),
});
console.log('\n[features] bundle ready');

const browserExecutable = [
  process.env.REMOTION_BROWSER,
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
].find((candidate) => candidate && existsSync(candidate));
if (!browserExecutable) throw new Error('Chrome not found. Set REMOTION_BROWSER.');

for (const [compositionId, { frames, video }] of Object.entries(COMPOSITIONS)) {
  const composition = await selectComposition({ serveUrl, id: compositionId, browserExecutable });
  console.log('[features] composition:', composition.id, composition.width, 'x', composition.height);

  for (const frame of frames) {
    const output = path.join(outDir, `features-${compositionId}-${String(frame).padStart(3, '0')}.png`);
    await renderStill({ serveUrl, composition, output, frame, browserExecutable });
    console.log('[features] still', compositionId, frame, '->', statSync(output).size, 'bytes');
  }

  if (video) {
    const videoPath = path.join(outDir, video);
    await renderMedia({
      serveUrl,
      composition,
      codec: 'h264',
      outputLocation: videoPath,
      browserExecutable,
      onProgress: ({ progress }) =>
        process.stdout.write(`\r[features] video ${Math.round(progress * 100)}%   `),
    });
    console.log('\n[features] video:', videoPath, statSync(videoPath).size, 'bytes');
  }
}

console.log('[features] DONE');