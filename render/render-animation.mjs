import path from 'node:path';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileTailwindCss } from './tailwind-v4.mjs';
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const sceneFile = path.join(projectRoot, 'examples', 'audio-animation-scene.tsx');
const generatedDir = path.join(here, '.generated');
const publicAudioDir = path.join(here, 'public', 'audio');
const outDir = path.join(here, 'out');

const STILL_FRAMES = [45, 90, 135, 165];

// Реальные медиа: музыка (SoundHelix, CC) и короткий SFX-«pop» (Google Sound Library).
const AUDIO_ASSETS = [
  { file: 'music.mp3', url: 'https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3' },
  { file: 'pop.ogg', url: 'https://actions.google.com/sounds/v1/cartoon/pop.ogg' },
];

for (const dir of [generatedDir, publicAudioDir, outDir]) mkdirSync(dir, { recursive: true });
if (!existsSync(sceneFile)) throw new Error(`Scene not found: ${sceneFile}`);

console.log('[animation] downloading audio assets...');
for (const asset of AUDIO_ASSETS) {
  const target = path.join(publicAudioDir, asset.file);
  if (existsSync(target) && statSync(target).size > 0) {
    console.log('[animation] cached:', asset.file, statSync(target).size, 'bytes');
    continue;
  }
  const response = await fetch(asset.url);
  if (!response.ok) throw new Error(`Failed to download ${asset.url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  writeFileSync(target, bytes);
  console.log('[animation] downloaded:', asset.file, bytes.length, 'bytes');
}

// Tailwind-утилиты, использованные в сцене.
console.log('[animation] compiling tailwind utilities...');
const source = readFileSync(sceneFile, 'utf8');
const tailwindCss = await compileTailwindCss(source);

writeFileSync(
  path.join(generatedDir, 'animation-scene.ts'),
  `// AUTO-GENERATED by render/render-animation.mjs. Do not edit.\n` +
    `export const source = ${JSON.stringify(source)};\n` +
    `export const css = ${JSON.stringify(tailwindCss)};\n`,
);
console.log('[animation] css bytes:', tailwindCss.length);

console.log('[animation] bundling...');
const serveUrl = await bundle({
  entryPoint: path.join(here, 'entry-animation.tsx'),
  publicDir: path.join(here, 'public'),
  outDir: path.join(here, 'bundle-animation'),
  onProgress: (progress) => process.stdout.write(`\r[animation] bundling ${progress}%   `),
});
console.log('\n[animation] bundle ready');

const browserExecutable = [
  process.env.REMOTION_BROWSER,
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
].find((candidate) => candidate && existsSync(candidate));
if (!browserExecutable) throw new Error('Chrome not found. Set REMOTION_BROWSER.');

const composition = await selectComposition({ serveUrl, id: 'AudioAnimation', browserExecutable });
console.log('[animation] composition:', composition.id, composition.width, 'x', composition.height);

for (const frame of STILL_FRAMES) {
  const output = path.join(outDir, `animation-frame-${String(frame).padStart(3, '0')}.png`);
  await renderStill({ serveUrl, composition, output, frame, browserExecutable });
  console.log('[animation] still', frame, '->', statSync(output).size, 'bytes');
}

const videoPath = path.join(outDir, 'sound-motion.mp4');
await renderMedia({
  serveUrl,
  composition,
  codec: 'h264',
  outputLocation: videoPath,
  browserExecutable,
  onProgress: ({ progress }) =>
    process.stdout.write(`\r[animation] video ${Math.round(progress * 100)}%   `),
});
console.log('\n[animation] video:', videoPath, statSync(videoPath).size, 'bytes');
console.log('[animation] DONE');
